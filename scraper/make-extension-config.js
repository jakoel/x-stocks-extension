// Generates ../turso-config.js (the extension's fallback credentials) from turso.json.
// Values are not printed. Re-run whenever turso.json changes: node make-extension-config.js
const fs = require('fs');
const path = require('path');
const c = JSON.parse(fs.readFileSync(path.join(__dirname, 'turso.json'), 'utf8'));
const out = `// Generated by scraper/make-extension-config.js - do not commit\nconst TURSO_CONFIG = ${JSON.stringify({ url: c.url, authToken: c.auth_token })};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'turso-config.js'), out);
console.log('Wrote turso-config.js');
